    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
         String userid=JcReceptionist.getSelectedItem().toString();
         String username=txtReceptionist.getText();
         try
         {
             boolean result=ReceptionistDAO.deleteReceptionist(userid,username);
             if(result)
             {
                  JOptionPane.showMessageDialog(null,"Receptionist Deleted Succesfully!");
                  JcReceptionist.removeItemAt(JcReceptionist.getSelectedIndex());
                  if(JcReceptionist.getItemCount()==0)
                      btnDelete.setEnabled(false);
                  return;
             }
              JOptionPane.showMessageDialog(null,"Receptionist Not Delete!");
         }
          catch(SQLException ex)
        {
              JOptionPane.showMessageDialog(null,"DB Error","Error",JOptionPane.ERROR_MESSAGE);
              ex.printStackTrace();
        }
    }//GEN-LAST:event_btnDeleteActionPerformed

