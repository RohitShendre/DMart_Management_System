    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
      int row=Ptable.getSelectedRow();
      
      if(row==-1){
          JOptionPane.showMessageDialog(null,"Please Select A Product!","Error!",JOptionPane.INFORMATION_MESSAGE);
          return;
      }
      String pid=tm.getValueAt(row,0).toString();
      try{
          if(ProductDAO.deleteProduct(pid)){
              JOptionPane.showMessageDialog(null,"Product Deleted Successfully!","Success!",JOptionPane.INFORMATION_MESSAGE);
              txtid.setText("");
              tm.setRowCount(0);
              showProductData();
          }
          else
          {
               JOptionPane.showMessageDialog(null,"Product Not Deleted!","Error!",JOptionPane.ERROR_MESSAGE);
          }
          
      }
       catch(SQLException ex)
        {
            JOptionPane.showMessageDialog(null,"Error Database","DB Error!",JOptionPane.ERROR_MESSAGE);
            ex.printStackTrace();
        }
    }//GEN-LAST:event_btnDeleteActionPerformed

