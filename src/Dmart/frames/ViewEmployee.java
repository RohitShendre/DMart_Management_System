    private void showEmpData() {
        try{
            List<EmployeePojo> empList=EmployeeDAO.getAllEmployees();
           DefaultTableModel tm=(DefaultTableModel) TblEmp.getModel();
           tm.setRowCount(0);
           Object [] rows=new Object[5];
           for(EmployeePojo emp:empList)
           {
               rows[0]=emp.getEmpid();
               rows[1]=emp.getEmpname();
               rows[2]=emp.getMobile_no();
               rows[3]=emp.getJob();
               rows[4]=emp.getSalary();
               tm.addRow(rows);
               
           }
        }
        catch(SQLException ex)
        {
            JOptionPane.showMessageDialog(null,"Error Database","DB Error!",JOptionPane.ERROR_MESSAGE);
            ex.printStackTrace();
        }
    }
