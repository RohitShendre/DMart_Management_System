    private void btnloginActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnloginActionPerformed
        if(!validateInputs())
        {
            JOptionPane.showMessageDialog(null,"please Fill All The Fields!","Incomplete data!",JOptionPane.ERROR_MESSAGE);
            return;
        }
        String UserType=getUserType();
        if(getUserType()==null)
        {
            JOptionPane.showMessageDialog(null,"Please Select Role!","Incomplete data",JOptionPane.ERROR_MESSAGE);
            return;
        }
        UserPojo u= new UserPojo();
        u.setUseid(userid);
        u.setPassword(password);
        u.setUsertype(UserType);
        try
        {
            boolean result = UserDAO.validateUser(u);
            if(result==false)
            {
                JOptionPane.showMessageDialog(null,"Invalid Username/Password/Role!","ERROR!",JOptionPane.ERROR_MESSAGE);
                return;
            }
            UserProfile.setUserid(userid);
            UserProfile.setUsertype(UserType);
            
            if(rbmanager.isSelected())
            {
               Manager mframe = new Manager();
               mframe.setVisible(true);
               this.dispose();
            }
            else
            {
               Receptionist rframe = new Receptionist();
               rframe.setVisible(true);
               this.dispose();
            }
        }
        catch(SQLException ex)
        {
            JOptionPane.showMessageDialog(null,"Error Database","DB Error!",JOptionPane.ERROR_MESSAGE);
            ex.printStackTrace();
        }                                       

    }//GEN-LAST:event_btnloginActionPerformed

