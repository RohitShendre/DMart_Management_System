    private void loadBill() {
        try
        {
            tm.setRowCount(0);
            txtRcpsid.setText(OrderDAO.getOrderReceptionist(orderId));
            
            ArrayList<Object[]>al=OrderDAO.viewBillDitails(orderId);
            double subtotal=0;
            double productTax=0;
            for(Object[]row:al)
            {
                tm.addRow(new Object[]{
                    row[0],row[1],row[2],row[3],row[4]
            });
                double total=((Number)row[4]).doubleValue();
                int tax=((Number)row[5]).intValue();
                
                subtotal+=total;
                productTax+=total*tax/100.0;
            }
            double grandtotal=subtotal+productTax;
            
            txtsubtotal.setText(String.format("%.2f", subtotal));
            txtptax.setText(String.format("%2f", productTax));
            txtgrtotal.setText(String.format("%.2f", grandtotal));
            
        }
        catch(SQLException ex)
        {
             JOptionPane.showMessageDialog(null,"Error Database","DB Error!",JOptionPane.ERROR_MESSAGE);
             ex.printStackTrace();
        }
    }
    

