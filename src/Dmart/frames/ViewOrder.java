    private void btnBackActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBackActionPerformed
          if("Manager".equalsIgnoreCase(role))
          {
              Manager m=new Manager();
              m.setVisible(true);
              this.dispose();
          }
          else if("Receptionist".equalsIgnoreCase(role))
          {
              Receptionist r=new Receptionist();
              r.setVisible(true);
              this.dispose();
          }
          else
          {
              JOptionPane.showMessageDialog(null, "User Type Not Found");
          }
    }//GEN-LAST:event_btnBackActionPerformed

    private void btnViewbillActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnViewbillActionPerformed
       int rows=TblOrder.getSelectedRow();
       
       if(rows==-1)
       {
           JOptionPane.showMessageDialog(null, "Please Select Order!");
           return;
       }
       String orderId=TblOrder.getValueAt(rows, 0).toString();
       
       Viewbill vb=new Viewbill(orderId,"ViewOrder");
       vb.setVisible(true);
       this.dispose();
    }//GEN-LAST:event_btnViewbillActionPerformed

