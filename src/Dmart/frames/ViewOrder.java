    private void loadOrders() {
        try
        {
            tm.setRowCount(0);
            ArrayList<Object[]> al=OrderDAO.getAllOrders(role,UserProfile.getUserid());
            
            for(Object[]rows:al)
            {
                tm.addRow(rows);
              
            }
        }
        catch(SQLException ex)
        {
            JOptionPane.showMessageDialog(null,"DB Error!");
            ex.printStackTrace();
        }
     
    }

