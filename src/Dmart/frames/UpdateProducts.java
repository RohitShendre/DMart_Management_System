    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
        if(!validateInputs())
        {
            JOptionPane.showMessageDialog(null,"Please Fill All The Fields");
            return;
        }
        try
        {
            int n=jctax.getSelectedItem().toString().trim().length();
            int tax= Integer.parseInt(jctax.getSelectedItem().toString().substring(0,n-1));
            ProductsPojo p= new ProductsPojo();
            p.setProductId(txtid.getText().trim());
            p.setProductName(txtname.getText().trim());
            p.setProductCompany(txtcompany.getText().trim());
            p.setProductPrice(Double.parseDouble(txtprice.getText().trim()));
            p.setOurPrice(Double.parseDouble(txtourprice.getText().trim()));
            p.setTax(tax);
            p.setQuantity(Integer.parseInt(txtQuantity.getText().trim()));
            boolean result=ProductDAO.UpdateProduct(p);
            if(result)
            {
                JOptionPane.showMessageDialog(null,"Product Updated Successfully!!");
                cleartaxt();
                showProductData();
                return;
                
            }
             JOptionPane.showMessageDialog(null,"Product Not Updated !");
        }
         catch(SQLException ex)
        {
            JOptionPane.showMessageDialog(null,"Error Database","DB Error!",JOptionPane.ERROR_MESSAGE);
            ex.printStackTrace();
        }
         catch(NumberFormatException ex)
        {
            JOptionPane.showMessageDialog(null,"Please Fill Numeric Data!","Error!",JOptionPane.ERROR_MESSAGE);
            ex.printStackTrace();
        }
    }//GEN-LAST:event_btnUpdateActionPerformed
 
