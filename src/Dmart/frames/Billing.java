    private void btnremoveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnremoveActionPerformed
         int rows=Ptable.getSelectedRow();
         if(rows==-1)
         {
             JOptionPane.showMessageDialog(null,"Please Select Row!");
             return;
         }
         int modelrow=Ptable.convertColumnIndexToModel(rows);
         int qty=Integer.parseInt(tm.getValueAt(modelrow, 6).toString());
         
         if(qty>1)
         {
             qty=qty-1;
             tm.setValueAt(qty,modelrow, 6);
             double price=Double.parseDouble(tm.getValueAt(modelrow, 4).toString());
             
             double tax=Double.parseDouble(tm.getValueAt(modelrow, 5).toString().replace("%", ""));
             double total=price*qty;
             total=total+(total*tax/100);
             
             tm.setValueAt(total,modelrow, 7);
         }
         else
         {
             tm.removeRow(modelrow);
             al.remove(modelrow);
         }
    }//GEN-LAST:event_btnremoveActionPerformed

