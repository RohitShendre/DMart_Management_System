    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddActionPerformed
          int result= validateInputs();
          if(result==0)
          {
               JOptionPane.showMessageDialog(null,"password must be atleast 4 characters long");
               return;
          }
          if(result==-1)
          {
              JOptionPane.showMessageDialog(null,"UserId cannot be left blank");
              return;
          }
          char []pwd=txtPassword.getPassword();
          char []repwd=txtRePassword.getPassword();
          String spwd=String.valueOf(pwd);
          String srepwd=String.valueOf(repwd);
          if(isPassword(spwd,srepwd)==false)
          {
              JOptionPane.showMessageDialog(null,"passwords do not match");
              return;
          }
          try
          {
              String id=JcEmpId.getSelectedItem().toString();
              String userid=txtUserId.getText().trim();
              String username=txtEmployeename.getText();
              UserPojo u =new UserPojo();
              u.setEmpid(id);
              u.setUseid(userid);
              u.setUsername(username);
              u.setPassword(spwd);
              u.setUsertype("Receptionist");
              boolean status=ReceptionistDAO.addReceptionist(u);
              if(status)
              {
                  JOptionPane.showMessageDialog(null,"Receptionist Added Succesfully!");
                  clearText();
                  loadReceptionistDatails();
                  return;
              }
              JOptionPane.showMessageDialog(null,"Record not Added !");
          }
           catch(SQLException ex)
        {
            JOptionPane.showMessageDialog(null,"Error Database","DB Error!",JOptionPane.ERROR_MESSAGE);
            ex.printStackTrace();
        }
                  
    }//GEN-LAST:event_btnAddActionPerformed

