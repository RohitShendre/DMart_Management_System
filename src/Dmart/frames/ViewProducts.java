private void showProductData() {
        try{
            List<ProductsPojo> PList=ProductDAO.getAllProducts();
            if(PList.isEmpty())
            {
                 JOptionPane.showMessageDialog(null,"No product Present In Stock");
                 return;
            }
           Object [] rows=new Object[7];
           tm=(DefaultTableModel)Ptable.getModel();
           tm.setRowCount(0);
           for(ProductsPojo p:PList)
           {
               rows[0]=p.getProductId();
               rows[1]=p.getProductName();
               rows[2]=p.getProductCompany();
               rows[3]=p.getProductPrice();
               rows[4]=p.getOurPrice();
               rows[5]=p.getTax()+"%";
               rows[6]=p.getQuantity();
               tm.addRow(rows);
               
           }
        }
        catch(SQLException ex)
        {
            JOptionPane.showMessageDialog(null,"Error Database","DB Error!",JOptionPane.ERROR_MESSAGE);
            ex.printStackTrace();
        }
    }
