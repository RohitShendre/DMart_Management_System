    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
         if(!validateInputs())
             return;
         
         try
         {
             String userid=JcReceptionist.getSelectedItem().toString();
             boolean result=ReceptionistDAO.updatePassword(userid,password);
             if(result)
             {
                  JOptionPane.showMessageDialog(null,"Password Changed Successfully");
                  cleartaxt();
                  JcReceptionist.setSelectedIndex(0);
                  return;
             }
              JOptionPane.showMessageDialog(null,"Password not Changed!");
              cleartaxt();
         }
          catch(SQLException ex)
        {
              JOptionPane.showMessageDialog(null,"DB Error","Error",JOptionPane.ERROR_MESSAGE);
              ex.printStackTrace();
        }
    }//GEN-LAST:event_btnUpdateActionPerformed

