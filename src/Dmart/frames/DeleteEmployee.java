 private void getEmployees() {
        try
      {
            Jcempid.removeAllItems();
            List<String> allEmpId=EmployeeDAO.getAllEmpId();
            for(String id:allEmpId)
            {
                Jcempid.addItem(id);
                
            }
        }
        catch(SQLException ex)
        {
            JOptionPane.showMessageDialog(null,"Error Database","DB Error!",JOptionPane.ERROR_MESSAGE);
            ex.printStackTrace();
        }
    }
    private boolean validateInputs()
    {
        return !(txtEmpname.getText().isEmpty()|| txtMobileno.getText().isEmpty()|| txtSalary.getText().isEmpty());
  }
