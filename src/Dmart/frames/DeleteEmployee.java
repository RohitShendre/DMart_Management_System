    private void JcempidActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_JcempidActionPerformed
         try
        {
            String empid=Jcempid.getSelectedItem().toString();
            EmployeePojo e=EmployeeDAO.findEmpById(empid);
            txtEmpname.setText(e.getEmpname());
            txtMobileno.setText(e.getMobile_no());
            txtSalary.setText(String.valueOf(e.getSalary()));
            Jcjob.setSelectedItem(e.getJob());
        }
          catch(SQLException ex)
        {
            JOptionPane.showMessageDialog(null,"Error Database","DB Error!",JOptionPane.ERROR_MESSAGE);
            ex.printStackTrace();
        }
                                 
    }//GEN-LAST:event_JcempidActionPerformed

    private void btnRemoveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRemoveActionPerformed
          if(!validateInputs())
         {
             JOptionPane.showMessageDialog(null,"Please Input All The Fields!","Error",JOptionPane.ERROR_MESSAGE);
             return;
         }
         try
         {
             String empid=Jcempid.getSelectedItem().toString();
             boolean result=EmployeeDAO.DeleteEmployee(empid);
             if(result)
             {
                 JOptionPane.showMessageDialog(null,"Record Deleted Successfully","Record Deleted",JOptionPane.INFORMATION_MESSAGE);
             }
             else
             {
                  JOptionPane.showMessageDialog(null,"Record Deletion Not Done","Error",JOptionPane.ERROR_MESSAGE);
             }
         }
         catch(SQLException ex)
        {
            JOptionPane.showMessageDialog(null,"Error Database","DB Error!",JOptionPane.ERROR_MESSAGE);
            ex.printStackTrace();
        }
                                 
    }//GEN-LAST:event_btnRemoveActionPerformed

